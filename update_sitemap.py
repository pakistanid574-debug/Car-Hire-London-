#!/usr/bin/env python3
"""
Generate sitemap.xml for a static HTML website.
Run from the project root: python generate_sitemap.py
"""
from pathlib import Path
from datetime import datetime, timezone
from xml.etree.ElementTree import Element, SubElement, ElementTree, register_namespace

SITE_URL = "https://private-driver-no.vercel.app"
ROOT = Path(__file__).resolve().parent

# Edit this list as needed. Paths are relative to the project root.
EXCLUDE_PATHS = {
    "404.html",
    "test.html",
    "privacy-policy.html",  # remove this entry if you want it in the sitemap
}
EXCLUDE_DIRS = {
    ".git", ".vercel", "node_modules", "dist", "build", "assets", "images"
}

# Add any non-file routes here (for example, routes generated by a framework).
EXTRA_URLS = []

register_namespace("", "http://www.sitemaps.org/schemas/sitemap/0.9")
urlset = Element("{http://www.sitemaps.org/schemas/sitemap/0.9}urlset")
today = datetime.now(timezone.utc).date().isoformat()

def route_from_file(path: Path) -> str:
    relative = path.relative_to(ROOT).as_posix()
    if relative.lower() == "index.html":
        return "/"
    # Nested index.html becomes its directory route; other .html extensions are removed.
    if relative.lower().endswith("/index.html"):
        return "/" + relative[:-len("/index.html")].strip("/")
    return "/" + relative[:-len(".html")]

# Always add homepage first (only if index.html exists; otherwise still add root URL).
homepage = SubElement(urlset, "url")
SubElement(homepage, "loc").text = SITE_URL + "/"
SubElement(homepage, "lastmod").text = today

seen = {SITE_URL + "/"}

for file in sorted(ROOT.rglob("*.html")):
    relative = file.relative_to(ROOT).as_posix()
    parts = set(file.relative_to(ROOT).parts)
    if parts & EXCLUDE_DIRS:
        continue
    if relative in EXCLUDE_PATHS or relative.lower() in {x.lower() for x in EXCLUDE_PATHS}:
        continue
    if file.name.lower() == "index.html" and file.parent == ROOT:
        continue  # homepage already added
    loc = SITE_URL + route_from_file(file)
    if loc in seen:
        continue
    seen.add(loc)
    entry = SubElement(urlset, "url")
    SubElement(entry, "loc").text = loc
    SubElement(entry, "lastmod").text = today

for route in EXTRA_URLS:
    loc = SITE_URL + (route if route.startswith("/") else "/" + route)
    if loc in seen:
        continue
    seen.add(loc)
    entry = SubElement(urlset, "url")
    SubElement(entry, "loc").text = loc
    SubElement(entry, "lastmod").text = today

output = ROOT / "sitemap.xml"
ElementTree(urlset).write(output, encoding="utf-8", xml_declaration=True)
print(f"Sitemap generated: {output} ({len(seen)} URLs)")
